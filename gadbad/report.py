"""Human-readable output: terminal text and a Markdown report for complaints."""

from __future__ import annotations

from datetime import datetime, timezone

from . import __version__
from .analyzer import Finding, Report

SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}

SMS_APP_NOTE = {
    "en": "Context:  declares every component a default SMS app needs, so SMS access is expected and scored lower.",
    "hi": "संदर्भ:   इसमें डिफ़ॉल्ट SMS ऐप के सभी ज़रूरी हिस्से हैं, इसलिए SMS अनुमति अपेक्षित है और उसे कम अंक दिए गए हैं।",
}


def mask_token(token: str) -> str:
    """Show enough of a bot token to identify it without printing all of it."""
    bot_id, _, secret = token.partition(":")
    return f"{bot_id}:{secret[:4]}…{secret[-2:]}" if secret else token


def _sorted(report: Report) -> list[Finding]:
    return sorted(report.findings, key=lambda f: SEVERITY_ORDER[f.severity])


def to_text(report: Report, lang: str = "en") -> str:
    lines = [
        f"File:     {report.file}",
        f"SHA-256:  {report.sha256}",
    ]
    if report.package:
        lines.append(f"Package:  {report.package}")
    lines.append(f"Verdict:  {report.verdict.upper()}  (risk score {report.score}/100)")
    if report.is_sms_app:
        lines.append(SMS_APP_NOTE[lang])
    lines.append("")
    for f in _sorted(report):
        lines.append(f"  [{f.severity.upper():6}] {f.title}")
        lines.append(f"           {f.explain(lang)}")
    if report.findings:
        lines.append("")
    if report.telegram_tokens:
        lines.append("Telegram bots: " + ", ".join(mask_token(t) for t in report.telegram_tokens))
    for label, items in (("IP endpoints", report.ip_endpoints), ("Firebase", report.firebase_urls)):
        if items:
            lines.append(f"{label}: " + ", ".join(items[:5]))
    lines.append("")
    lines.append(report.advice(lang))
    return "\n".join(lines)


def to_markdown(report: Report) -> str:
    """A report a victim or investigator can attach to a cybercrime complaint."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# Suspicious APK report",
        "",
        f"Generated by Gadbad {__version__} on {now}. Static analysis only: the app was never installed or run.",
        "",
        "## File",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| File name | `{report.file}` |",
        f"| Size | {report.size_bytes:,} bytes |",
        f"| SHA-256 | `{report.sha256}` |",
        f"| SHA-1 | `{report.sha1}` |",
        f"| MD5 | `{report.md5}` |",
        f"| Package name | `{report.package or 'unknown'}` |",
        "",
        "## Verdict",
        "",
        f"**{report.verdict}**, risk score {report.score}/100.",
        "",
    ]
    if report.is_sms_app:
        out += [SMS_APP_NOTE["en"].replace("Context:  ", "Context: "), ""]
    if report.findings:
        out += ["## Findings", "", "| Severity | Finding | Evidence |", "|---|---|---|"]
        for f in _sorted(report):
            out.append(f"| {f.severity} | {f.title}: {f.explain('en')} | `{f.evidence}` |")
        out.append("")
    indicators = (
        [("Telegram bot", mask_token(t)) for t in report.telegram_tokens]
        + [("IP endpoint", u) for u in report.ip_endpoints]
        + [("Firebase", u) for u in report.firebase_urls]
    )
    if indicators:
        out += ["## Network indicators", "", "| Type | Value |", "|---|---|"]
        out += [f"| {kind} | `{value}` |" for kind, value in indicators]
        out.append("")
    out += [
        "## What to do",
        "",
        report.advice("en"),
        "",
        report.advice("hi"),
        "",
        "Report online at https://cybercrime.gov.in or call the national cybercrime helpline **1930**.",
        "",
    ]
    return "\n".join(out)
